import assert from 'node:assert/strict';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const url = process.env.PORTFOLIO_URL || 'http://127.0.0.1:5173';
try {
  await page.goto(`${url}/#projects`);
  await page.locator('.project-compendium').waitFor();
  assert.equal(await page.locator('.project-persona').count(), 1, 'Reusable persona occupies the existing art slot');
  await page.screenshot({ path: '/tmp/project-persona-initial.png' });
  await page.waitForTimeout(1000);
  const image = page.locator('.project-persona img');
  assert.ok(await image.evaluate(el => el.complete && el.naturalWidth > 0), 'Final artwork loads');
  assert.ok((await image.getAttribute('src')).endsWith('/experimentos-persona.png'));
  assert.equal(await page.locator('.project-persona img').count(), 1, 'Single-image artwork');
  assert.equal(await image.evaluate(el => getComputedStyle(el).pointerEvents), 'none');
  const anchor = page.locator('.project-art-anchor');
  const bounds = await anchor.boundingBox();
  const idle = page.locator('.project-persona-idle').first();
  const before = await idle.evaluate(el => getComputedStyle(el).transform);
  await page.waitForTimeout(350);
  assert.notEqual(await idle.evaluate(el => getComputedStyle(el).transform), before, 'Idle moves');
  assert.deepEqual(await anchor.boundingBox(), bounds, 'Idle never changes layout');
  const rows = page.locator('button.project-choice');
  await rows.nth(1).click();
  await page.waitForTimeout(350);
  await rows.first().click();
  await page.waitForTimeout(350);
  const entering = await page.locator('.project-persona-entry').evaluate(el => getComputedStyle(el).transform);
  await page.waitForTimeout(750);
  assert.notEqual(await page.locator('.project-persona-entry').evaluate(el => getComputedStyle(el).transform), entering, 'Reselection enters then settles');
  const float = await idle.evaluate(el => {
    const animation = el.getAnimations()[0];
    animation.pause();
    const timing = animation.effect.getTiming();
    animation.currentTime = timing.delay + timing.duration / 2;
    const matrix = new DOMMatrix(getComputedStyle(el).transform);
    animation.play();
    return { y: matrix.m42, scale: matrix.a, rotation: matrix.b, duration: timing.duration };
  });
  assert.deepEqual(float, { y: -6, scale: 1, rotation: 0, duration: 4600 });
  await page.getByRole('button', { name: 'Motion on', exact: true }).click();
  const stopped = await idle.evaluate(el => getComputedStyle(el).transform);
  await page.waitForTimeout(150);
  assert.equal(await idle.evaluate(el => getComputedStyle(el).transform), stopped, 'Motion control stops idle');
  await page.getByRole('button', { name: 'Motion off', exact: true }).click();
  await page.waitForTimeout(100);
  assert.equal(await page.locator('.project-persona-entry').evaluate(el => getComputedStyle(el).transform), 'none', 'Resume must not replay entrance');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.waitForTimeout(100);
  assert.equal(await idle.evaluate(el => getComputedStyle(el).animationName), 'none');
  for (const [width, height] of [[1920,1080],[1440,900],[1366,768],[1024,768],[768,1024],[390,844],[320,568]]) {
    await page.setViewportSize({ width, height });
    await page.waitForTimeout(150);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'No horizontal overflow');
    const art = await anchor.boundingBox();
    assert.ok(art.width > 0 && art.height > 0 && art.x + art.width > width / 2, 'Stable right-side bounds');
    await page.screenshot({ path: `/tmp/project-persona-${width}.png`, fullPage: true });
  }
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.evaluate(async () => {
    const source = performance.getEntriesByType('resource').find(entry => entry.name.includes('/src/data/portfolio.js'));
    const { projectData } = await import(source.name);
    const src = projectData[0].persona.image;
    projectData[0].persona = { mode: 'layers', layers: { body: src, core: src, shards: src, energy: src } };
  });
  await rows.nth(1).click();
  await page.waitForTimeout(100);
  await rows.first().click();
  await page.waitForTimeout(100);
  assert.equal(await page.locator('.project-persona-layer').count(), 4, 'Layer config renders all four layers');
  assert.equal(await page.locator('.project-persona-entry').evaluate(el => getComputedStyle(el).transform), 'none', 'Reduced motion selection has no entrance transform');
  const canvas = await page.locator('.project-persona img').evaluateAll(images => images.map(el => ({width:el.clientWidth,height:el.clientHeight,left:el.offsetLeft,top:el.offsetTop,fit:getComputedStyle(el).objectFit})));
  assert.ok(canvas.every(item => JSON.stringify(item) === JSON.stringify(canvas[0])), 'Layers share one aligned canvas');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.waitForTimeout(100);
  assert.equal(await page.locator('.project-persona-entry').evaluate(el => getComputedStyle(el).transform), 'none', 'Preference change does not replay entrance');
  const tracks = await page.locator('.project-persona-idle').evaluateAll(elements => elements.map(el => {
    const animation = el.getAnimations()[0];
    animation.pause();
    animation.currentTime = 600;
    const start = { transform:getComputedStyle(el).transform,opacity:getComputedStyle(el).opacity };
    animation.currentTime = 600 + animation.effect.getTiming().duration / 2;
    return { start, mid: {transform:getComputedStyle(el).transform,opacity:getComputedStyle(el).opacity} };
  }));
  assert.ok(tracks.every(track => JSON.stringify(track.start) !== JSON.stringify(track.mid)), 'Each layer has its own idle motion');
  await rows.nth(1).click();
  await rows.nth(2).click();
  await rows.first().click();
  await page.waitForTimeout(1000);
  assert.equal(await page.locator('.project-persona-entry').count(), 1);
  assert.equal(await page.locator('.project-persona-entry').getAttribute('data-project'), 'experimentos', 'Rapid switches resolve to latest selection');
  console.log('Project Persona: asset, selection entrance, idle, stable bounds, pause, reduced motion and responsive checks passed.');
} finally { await browser.close(); }
