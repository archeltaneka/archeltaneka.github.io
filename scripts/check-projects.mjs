import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
const output = process.env.PROJECTS_CAPTURE_DIR || '.impeccable/review/projects';
page.on('pageerror', e => errors.push(e.message));
const url = process.env.PORTFOLIO_URL || 'http://127.0.0.1:5173';
try {
  await page.goto(url);
  await page.locator('.landing[data-intro="complete"]').waitFor();
  await page.getByRole('button', { name: 'Projects', exact: true }).hover();
  await page.waitForTimeout(250);
  await page.getByRole('button', { name: 'Projects', exact: true }).click();
  await page.locator('.project-compendium').waitFor({ state: 'visible', timeout: 4000 });
  await page.waitForFunction(() => location.hash === '#projects');
  await page.locator('.portfolio-scene[data-scene-state="PROJECTS_IDLE"]').waitFor();
  const main = page.locator('.project-compendium');
  const rows = main.locator('button.project-choice');
  await rows.nth(1).focus();
  await page.keyboard.press('Enter');
  await page.waitForTimeout(800);
  assert.equal(await main.locator('.project-detail-name').innerText(), 'Cherébowl', 'Enter opens the focused row');
  await main.getByRole('button', { name: 'Project list', exact: true }).click();
  await page.waitForTimeout(350);
  assert.equal(await main.locator('.project-open, .project-keyboard-hint').count(), 0);
  await rows.first().hover();
  await page.waitForTimeout(800);
  const initialArt = await main.locator('.project-persona-entry').last().getAttribute('data-project');
  await rows.nth(1).hover();
  await page.waitForTimeout(800);
  assert.equal(await main.getAttribute('data-view'), 'select', 'Hover only previews');
  assert.equal(await rows.nth(1).getAttribute('data-selected'), 'true');
  assert.notEqual(await main.locator('.project-persona-entry').last().getAttribute('data-project'), initialArt, 'Hover changes illustration');
  await rows.nth(1).press('ArrowUp');
  assert.equal(await rows.nth(1).getAttribute('data-selected'), 'true', 'Arrow keys do not select');
  await main.locator('.project-art-anchor').evaluate(el => { window.retainedProjectArt = el; });
  await rows.first().click();
  await page.waitForTimeout(800);
  assert.equal(await main.getAttribute('data-view'), 'details');
  assert.ok(await main.locator('.project-art-anchor').evaluate(el => el === window.retainedProjectArt));
  assert.equal(await main.locator('.technology-entry').count(), 8);
  assert.equal(await main.locator('.project-duration').count(), 0);
  assert.equal(await main.locator('.project-header-plane .technology-categories').count(), 1);
  await main.getByRole('button', { name: 'Next project', exact: true }).click();
  await page.waitForTimeout(450);
  assert.equal(await main.locator('.project-detail-name').innerText(), 'Cherébowl');
  await main.getByRole('button', { name: 'Next project', exact: true }).click();
  await page.waitForTimeout(450);
  assert.equal(await main.locator('.project-detail-name').innerText(), 'Joint Intent & Slot Detection');
  await page.keyboard.press('ArrowRight');
  await page.keyboard.press('Escape');
  assert.equal(await main.getAttribute('data-view'), 'details', 'Escape does not close details');
  assert.equal(await main.locator('.project-detail-name').innerText(), 'Joint Intent & Slot Detection', 'Arrow keys do not switch details');
  await main.getByRole('button', { name: 'Project list', exact: true }).click();
  await page.waitForTimeout(400);
  assert.equal(await rows.nth(2).evaluate(el => el === document.activeElement), true);
  await fs.mkdir(output, { recursive: true });
  for (const [width, height] of [[1440,900],[1280,720],[1200,800],[1024,768],[768,1024],[390,844],[320,568]]) {
    await page.setViewportSize({ width, height });
    await rows.first().hover();
    await page.waitForTimeout(350);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `select overflow ${width}`);
    assert.ok(await page.evaluate(() => document.documentElement.scrollHeight <= innerHeight), `Project list fits viewport ${width}x${height}`);
    assert.equal(await main.locator('.projects-blue-wedge').evaluate(el => getComputedStyle(el).visibility), 'hidden', 'Selection keeps uninterrupted underwater background');
    await page.screenshot({ path: `${output}/select-${width}.png`, fullPage: true });
    await rows.first().click();
    await page.waitForTimeout(800);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `detail overflow ${width}`);
    assert.equal(await main.locator('.projects-blue-wedge').evaluate(el => getComputedStyle(el).visibility), 'visible', 'Diagonal fields appear only in details');
    if (width >= 1024 && height >= 700) {
      // Short laptop screens scroll naturally to preserve the requested header gap.
      if (height > 800) assert.ok(await page.evaluate(() => document.documentElement.scrollHeight <= innerHeight), `Desktop details fit viewport ${width}`);
      assert.ok(await main.evaluate(el => el.querySelector('.technology-panel').getBoundingClientRect().top > el.querySelector('.project-technology-band').getBoundingClientRect().bottom), 'Technology panel clears the blue header band');
      assert.ok(await main.evaluate(el => el.querySelector('.project-actions').getBoundingClientRect().bottom < el.querySelector('.project-return').getBoundingClientRect().top), 'Actions do not collide with footer');
    }
    assert.ok(await main.locator('a').evaluateAll(links => links.every(a => a.target === '_blank' && a.rel.includes('noopener'))));
    assert.equal(await main.evaluate(el => el.scrollTop), 0, `No clipped internal scroll at ${width}`);
    assert.ok(await main.locator('.project-actions').evaluate(el => el.getBoundingClientRect().bottom <= document.documentElement.scrollHeight), 'Actions reachable in document flow');
    await page.evaluate(() => scrollTo({ top: 0, behavior: 'instant' }));
    await page.screenshot({ path: `${output}/detail-${width}.png`, fullPage: true });
    await main.getByRole('button', { name: 'Project list', exact: true }).click();
    await page.waitForTimeout(350);
    const focused = await page.evaluate(() => { const r = document.activeElement.getBoundingClientRect(); return r.top >= 0 && r.bottom <= innerHeight; });
    assert.ok(focused, `Return focus stays in view at ${width}`);
  }
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await rows.first().click();
  await main.getByRole('button', { name: 'Next project' }).click();
  await page.waitForTimeout(50);
  assert.equal(await main.locator('.project-detail-name').innerText(), 'Cherébowl');
  await main.getByRole('button', { name: 'Main menu', exact: true }).click();
  await page.waitForFunction(() => location.hash === '#home');
  await page.goBack();
  await page.waitForFunction(() => location.hash === '#projects');
  await page.reload();
  await main.waitFor({ state: 'visible' });
  assert.equal(await page.locator('.page-load-dive').count(), 0);
  assert.deepEqual(errors, []);
  const touch = await browser.newPage({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, reducedMotion: 'reduce' });
  await touch.goto(`${url}/#projects`);
  await touch.locator('.portfolio-scene[data-scene-state="PROJECTS_IDLE"]').waitFor();
  await touch.locator('button.project-choice').nth(1).tap();
  assert.equal(await touch.locator('.project-compendium').getAttribute('data-view'), 'details', 'One tap opens details');
  assert.equal(await touch.locator('.project-detail-name').innerText(), 'Cherébowl');
  await touch.close();
  console.log('Projects: navigation, hover previews, direct click, native keyboard access, technologies, seven responsive sizes, reduced motion and history passed.');
} finally { await browser.close(); }
