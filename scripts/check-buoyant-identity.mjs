const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:900}});
await page.goto(process.env.PORTFOLIO_URL || 'http://127.0.0.1:5173/');
await page.locator('.landing[data-intro="complete"]').waitFor();
await page.evaluate(()=>document.fonts.ready);
assert.equal(await page.locator('.carousel-name').first().innerText(),'ARCHEL TANEKA SUTANTO');
assert.equal(await page.locator('.landing-identity h1').getAttribute('class'),'sr-only');
const drift=page.locator('.buoyant-drift').first();
const transform=()=>drift.evaluate(el=>getComputedStyle(el).transform);
const start=await transform();
await page.waitForTimeout(250);
assert.notEqual(await transform(),start,'ambient drift changes transform');
const zone=page.locator('.buoyant-zone').first();
const text=zone.locator('.buoyant-text');
await zone.hover({position:{x:2,y:8}});
await page.waitForTimeout(120);
const pushed=await text.evaluate(el=>new DOMMatrixReadOnly(getComputedStyle(el).transform).e);
assert.ok(pushed>1,'hover pushes text away from left edge');
await page.screenshot({path:'/tmp/buoyant-hover.png'});
await page.mouse.move(1400,600);
await page.waitForTimeout(1700);
assert.equal(await text.evaluate(el=>el.getAnimations().length),0,'impulse settles and releases');
await zone.hover({position:{x:3,y:10}});
await page.getByRole('button',{name:'Pause animation',exact:true}).click();
assert.equal(await text.evaluate(el=>el.getAnimations().length),0,'pause cancels active impulse');
const frozen=await transform();
await page.waitForTimeout(200);
assert.equal(await transform(),frozen,'pause freezes ambient drift');
await page.getByRole('button',{name:'Resume animation',exact:true}).click();
await page.mouse.move(1400,600);
await zone.hover({position:{x:3,y:10}});
await page.emulateMedia({reducedMotion:'reduce'});
await page.waitForTimeout(80);
assert.equal(await text.evaluate(el=>el.getAnimations().length),0,'reduced motion cancels impulse');
assert.equal(await drift.evaluate(el=>getComputedStyle(el).animationName),'none');
await fs.mkdir('/tmp/buoyant-review',{recursive:true});
for(const [width,height] of [[1440,900],[1024,768],[390,844],[320,568]]) {
 await page.setViewportSize({width,height});
 await page.waitForTimeout(100);
 await page.screenshot({path:`/tmp/buoyant-review/${width}.png`,fullPage:true});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'no overflow '+width);
 if(width<900) assert.equal(await page.locator('.landing-identity h1').innerText(),'ARCHEL TANEKA SUTANTO');
}
console.log('PASS full-name carousel, desktop name removal, ambient drift, directional hover, settling, pause, dynamic reduced motion, four viewport captures');
await browser.close();
